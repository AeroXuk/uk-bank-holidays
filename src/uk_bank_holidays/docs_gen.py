"""Generate the reference pages in ``docs/generated`` from the source data."""

from pathlib import Path

HEADER = "<!-- Generated by `python -m uk_bank_holidays docs`. Do not edit by hand. -->\n\n"


def _sources_cell(ids, sources):
    links = []
    for i in ids:
        s = sources[i]
        text = f"[{s['title']}]({s['url']})" if s["url"] else s["title"]
        if s["archive_url"]:
            text += f" ([archive]({s['archive_url']}))"
        links.append(text)
    return "<br>".join(links)


def _years(rule):
    return f"{rule['valid_from_year'] or 'T.I.'} to {rule['valid_to_year'] or 'onwards'}"


def _regions(item):
    return ", ".join(
        r.replace("_", " ").title().replace("And", "&")
        for r in ("england_and_wales", "scotland", "northern_ireland")
        if item[r]
    )


def _describe(rule):
    p, kind = rule["parameters"], rule["rule_type"]
    if kind == "fixed_date":
        return f"Fixed date: {p['day']}/{p['month']}"
    if kind == "nth_weekday":
        return f"{p['weekday'].title()} number {p['n']} of month {p['month']}"
    if kind == "last_weekday":
        return f"Last {p['weekday'].title()} of month {p['month']}"
    if kind == "easter_offset":
        return f"Easter Sunday {p['days']:+d} days"
    return f"First {p['weekday'].title()} after the last {p['after_weekday'].title()} of month {p['month']}"


def _verified(item):
    return "yes" if item["verified"] else "**no**"


def render_rules(data: dict) -> str:
    out = [
        HEADER,
        "# Recurring rules\n\n",
        "| Rule id | Name | Years | Calculation | Regions | Verified | Sources |\n",
        "|---|---|---|---|---|---|---|\n",
    ]
    for r in data["rules"]:
        out.append(
            f"| `{r['rule_id']}` | {r['name']} | {_years(r)} | {_describe(r)} | {_regions(r)} | "
            f"{_verified(r)} | {_sources_cell(r['source_ids'], data['sources'])} |\n"
        )
    out.append(
        "\n## Moved dates\n\n| Rule id | Year | Date | Reason | Verified | Sources |\n|---|---|---|---|---|---|\n"
    )
    for o in data["overrides"]:
        out.append(
            f"| `{o['rule_id']}` | {o['year']} | {o['date']} | {o['reason']} | {_verified(o)} | "
            f"{_sources_cell(o['source_ids'], data['sources'])} |\n"
        )
    return "".join(out)


def render_proclamations(data: dict) -> str:
    out = [
        HEADER,
        "# Royal proclamations\n\n",
        "| Date | Id | Reason | Regions | Verified | Sources |\n|---|---|---|---|---|---|\n",
    ]
    for p in data["proclamations"]:
        out.append(
            f"| {p['date']} | `{p['proclamation_id']}` | {p['reason']} | {_regions(p)} | "
            f"{_verified(p)} | {_sources_cell(p['source_ids'], data['sources'])} |\n"
        )
    return "".join(out)


def render_sources(data: dict) -> str:
    out = [HEADER, "# Sources\n\n| Id | Title | Publisher | Link | Archived |\n|---|---|---|---|---|\n"]
    for i, s in data["sources"].items():
        link = f"<{s['url']}>" if s["url"] else "(offline source)"
        archive = f"[{s['accessed']}]({s['archive_url']})" if s["archive_url"] else "not yet archived"
        out.append(f"| `{i}` | {s['title']} | {s['publisher']} | {link} | {archive} |\n")
    return "".join(out)


def write_docs(data: dict, docs_dir: Path) -> list[Path]:
    docs_dir.mkdir(parents=True, exist_ok=True)
    pages = {"rules.md": render_rules, "proclamations.md": render_proclamations, "sources.md": render_sources}
    written = []
    for name, render in pages.items():
        path = docs_dir / name
        path.write_text(render(data), encoding="utf-8")
        written.append(path)
    return written
